"""Conservative offline inspection of normally exported Orca Temperature G-code.

This reads bytes only. It generates, rewrites and executes no G-code. Reports
are evidence inputs; unresolved macros/config/filament suitability block readiness.
"""
from __future__ import annotations
import hashlib
import math
import re

CHOICES = [210, 205, 200]
MAX_ESTIMATED_SECONDS = 1200
NUMBER = r"[-+]?(?:\d+(?:\.\d*)?|\.\d+)"
SAFE_COMMANDS = frozenset(('G0','G1','G4','G21','G28','G90','G91','G92','M82','M83','M84','M104','M106','M107','M109','M117','M140','M190','M201','M203','M204','M205','M220','M221','M73','M400','M900'))

class GcodeError(ValueError): pass

def estimate_seconds(text):
    entries=re.findall(r'^; estimated printing time \(normal mode\) = (.+)$',text,re.M)
    if len(entries)!=1: raise GcodeError('Exactly one native normal-mode estimate is required')
    value=entries[0].strip()
    parts=re.findall(r'(\d+(?:\.\d+)?)\s*([dhms])',value)
    if not parts or re.sub(r'\d+(?:\.\d+)?\s*[dhms]\s*','',value):
        raise GcodeError('Native time estimate is unavailable or malformed')
    seen=set(); total=0.0
    for n,unit in parts:
        if unit in seen: raise GcodeError('Ambiguous native time estimate')
        seen.add(unit); total+=float(n)*{'d':86400,'h':3600,'m':60,'s':1}[unit]
    if not math.isfinite(total) or total<=0: raise GcodeError('Invalid native estimate')
    return total

def inspect(data:bytes, filename:str):
    if not isinstance(data,bytes) or not 0<len(data)<=20_000_000: raise GcodeError('G-code size unavailable')
    if not re.fullmatch(r'[^/\\\x00-\x1f]+\.gcode',filename) or '..' in filename: raise GcodeError('Unsafe filename')
    try: text=data.decode('utf-8',errors='strict')
    except UnicodeError as e: raise GcodeError('G-code is not UTF-8') from e
    # Generated-by text is an origin hint; exact native runtime/export evidence is separate.
    if not re.search(r'^; generated by OrcaSlicer ',text,re.M): raise GcodeError('Missing native Orca header')
    duration=estimate_seconds(text)
    xyz={a:None for a in 'XYZ'}; e=0.0; absolute=True; absolute_e=True; temp=None
    start_arguments=[]; bed_targets=[]; targets=[]; bands=[]; by_band={n:[] for n in CHOICES}; commands=[]; unresolved=set(); points=[]
    for line_num,line in enumerate(text.splitlines(),1):
        code=line.split(';',1)[0].strip()
        if not code: continue
        match=re.match(r'^([A-Za-z_][A-Za-z_0-9]*)(?:\s|$)',code)
        if not match: raise GcodeError(f'Unparsed command at line {line_num}')
        cmd=match.group(1).upper(); commands.append(cmd)
        rest=code[len(match.group(1)):].upper()
        if cmd in ('G0','G1','G2','G3','G92','M104','M109','M140','M190') and not re.fullmatch(r'\s*(?:[A-Z]'+NUMBER+r'\s*)*',rest):
            raise GcodeError('Malformed motion or heater command')
        if cmd in ('G2','G3'):
            raise GcodeError('Arc geometry requires separate qualification; endpoints are insufficient')
        if cmd=='G92' and any(a in rest for a in 'XYZ'):
            raise GcodeError('Coordinate rebasing is not qualified')
        fields={k:float(v) for k,v in re.findall(r'([A-Z])('+NUMBER+r')',code[len(match.group(1)):].upper())}
        if any(not math.isfinite(v) for v in fields.values()): raise GcodeError('Non-finite motion or temperature')
        if cmd not in SAFE_COMMANDS: unresolved.add(cmd)
        if cmd=='PRINT_START':
            start_arguments.append({k:float(v) for k,v in re.findall(r'([A-Za-z_]+)=('+NUMBER+r')',code)})
        if cmd in ('M140','M190'):
            if 'S' not in fields:raise GcodeError('Bed target unavailable')
            bed_targets.append(fields['S'])
        if cmd in ('M104','M109'):
            if 'T' in fields and fields['T']!=0: raise GcodeError('Multiple tool temperatures unsupported')
            setting=fields.get('S',fields.get('R'))
            if setting is None: raise GcodeError('Missing temperature target')
            temp=setting
            if temp>0 and (not targets or targets[-1]!=temp): targets.append(temp)
        if cmd=='G90': absolute=True
        if cmd=='G91': absolute=False
        if cmd=='M82': absolute_e=True
        if cmd=='M83': absolute_e=False
        if cmd=='G92':
            for a in 'XYZ':
                if a in fields: xyz[a]=fields[a]
            if 'E' in fields:e=fields['E']
        if cmd in ('G0','G1','G2','G3'):
            for a in 'XYZ':
                if a in fields:
                    if not absolute and xyz[a] is None:raise GcodeError('Relative motion begins from unavailable coordinates')
                    xyz[a]=fields[a] if absolute else xyz[a]+fields[a]
            delta=fields.get('E',e)-e if absolute_e else fields.get('E',0)
            if 'E' in fields:e=fields['E'] if absolute_e else e+fields['E']
            points.append(dict(xyz))
            if delta>0 and ('X' in fields or 'Y' in fields):
                if temp not in CHOICES: raise GcodeError('Extrusion without one of the three explicit temperatures')
                if not bands or bands[-1]!=temp: bands.append(temp)

                if xyz['Z'] is None:raise GcodeError('Extrusion Z position is unavailable')
                by_band[temp].append(xyz['Z'])
    if targets!=CHOICES or bands!=CHOICES: raise GcodeError('Expected exactly three descending explicit and extruding bands')
    if not points or any(not by_band[t] for t in CHOICES): raise GcodeError('Missing printable geometry')
    spans=[{'temperature_c':n,'min_z':min(by_band[n]),'max_z':max(by_band[n])} for n in CHOICES]
    if any(s['max_z']-s['min_z']<1 for s in spans): raise GcodeError('A band has no multi-layer geometry')
    if any(spans[i]['max_z']>spans[i+1]['min_z'] for i in (0,1)): raise GcodeError('Temperature bands overlap or reverse in Z')
    return {'schema':'helix-orca-temperature-gcode-inspection/v1','file':filename,'file_bytes':len(data),
        'file_sha256':hashlib.sha256(data).hexdigest(),'choices':list(CHOICES),
        'estimated_duration_s':duration,'within_first_test_limit':duration<=MAX_ESTIMATED_SECONDS,
        'target_10_to_20_minutes':600<=duration<=1200,'bands':spans,
        'motion_bounds':{a:[min(p[a] for p in points if p[a] is not None),max(p[a] for p in points if p[a] is not None)] for a in 'XYZ'},
        'unresolved_commands':sorted(unresolved),'start_arguments':start_arguments,'bed_targets_c':sorted(set(bed_targets)),'physical_ready':False}

def qualify(report, *, request, suitability):
    printer=request["printer"]
    """Bind reviewed private printer/filament/macro evidence, never infer suitability."""
    required={'file_sha256','printer','filament_range_c','motion_bounds','macro_sources_sha256','native_export_verified','printer_config_sha256','physical_printer_identity','macro_safety_reviewed','printer_safety_reviewed','startup_estimated_duration_s','startup_estimate_basis','start_required_arguments','bed_range_c'}
    if not isinstance(suitability,dict) or set(suitability)!=required: raise GcodeError('Suitability evidence unavailable')
    if suitability['macro_safety_reviewed'] is not True or suitability['printer_safety_reviewed'] is not True:
        raise GcodeError('Printer/macro safety review unavailable')
    if not re.fullmatch('[a-f0-9]{64}',suitability['physical_printer_identity']):raise GcodeError('Physical machine identity unavailable')
    for key in ('file','file_bytes','file_sha256','choices'):
        if request[key]!=report[key]:raise GcodeError('Request differs from inspected native file')
    if suitability['file_sha256']!=report['file_sha256'] or suitability['printer']!=printer or suitability['native_export_verified'] is not True:
        raise GcodeError('Suitability provenance mismatch')
    allowance=suitability['startup_estimated_duration_s']
    basis=suitability['startup_estimate_basis']
    if type(allowance) not in (int,float) or not math.isfinite(allowance) or allowance<0 or not isinstance(basis,str) or not basis.strip():
        raise GcodeError('Opaque macro/startup estimate is unavailable')
    total=report['estimated_duration_s']+allowance
    if not 600<=total<=1200:raise GcodeError('Combined estimate is outside the requested 10–20-minute target')
    starts=report['start_arguments']
    if len(starts)!=1 or not set(suitability['start_required_arguments']).issubset(starts[0]):
        raise GcodeError('PRINT_START arguments do not match the reviewed printer macro')
    bed_low,bed_high=suitability['bed_range_c']
    if any(not bed_low<=value<=bed_high for value in report['bed_targets_c']):raise GcodeError('Bed temperature exceeds reviewed bounds')
    if not report['within_first_test_limit']: raise GcodeError('Estimate exceeds the maximum 20 minutes')
    if not report['target_10_to_20_minutes']:raise GcodeError('Output is outside the requested 10–20-minute target')
    low,high=suitability['filament_range_c']
    if not all(type(n) in (int,float) and math.isfinite(n) for n in (low,high)) or not low<=200<=210<=high:
        raise GcodeError('Filament suitability is unqualified')
    if not re.fullmatch('[a-f0-9]{64}',suitability['printer_config_sha256']): raise GcodeError('Printer configuration unqualified')
    sources=suitability['macro_sources_sha256']
    if set(sources)!=set(report['unresolved_commands']) or any(not re.fullmatch('[a-f0-9]{64}',v) for v in sources.values()):
        raise GcodeError('Custom command behavior is unresolved')
    for a,bounds in report['motion_bounds'].items():
        limits=suitability['motion_bounds'][a]
        if not len(limits)==2 or not all(type(n) in (int,float) and math.isfinite(n) for n in limits) or not limits[0]<=bounds[0]<=bounds[1]<=limits[1]:
            raise GcodeError('Motion exceeds the qualified printer envelope')
    return {'schema':'helix-orca-temperature-gcode-qualification/v1',
        **{k:report[k] for k in ('file','file_bytes','file_sha256','choices','estimated_duration_s')},
        **{k:request[k] for k in ('request_id','origin_id','context_sha256')},
        'physical_printer_identity':suitability['physical_printer_identity'],'printer_config_sha256':suitability['printer_config_sha256'],'band_count':3,'temperature_order_verified':True,
        'native_estimated_duration_s':report['estimated_duration_s'],'startup_estimated_duration_s':allowance,'estimated_duration_s':total,
        'printer':printer,'suitable':True,'geometry_verified':True,'temperature_commands_verified':True,
        'file_identity_verified':True,'inspection_sha256':hashlib.sha256(__import__('json').dumps(report,sort_keys=True).encode()).hexdigest(),
        'suitability_sha256':hashlib.sha256(__import__('json').dumps(suitability,sort_keys=True).encode()).hexdigest()}
